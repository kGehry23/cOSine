/*!
 * @brief IRQ handler for IRQ0
 * @return None
 */
void handle_key_press()
{

    inb(0x60);

    if(inb(0x64)&0x1 == 1)
    {
        uint32_t res = inb(0x60);

        while(inb(0x64)&0x1 == 1)
        {
            res = res + inb(0x60);
        }
       
        if(res <= sizeof(key_codes)/sizeof(char))
            printf("%s", key_codes[res]);
        
    }

    //Send EOI to PIC
    outb(0x20, 0x20);
}
